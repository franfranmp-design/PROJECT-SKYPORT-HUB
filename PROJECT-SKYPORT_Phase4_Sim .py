import heapq
import random
import numpy as np
import matplotlib.pyplot as plt
import pandas as pd

"""
PROJECT SKYPORT-HUB: Discrete Event Simulation (DES) Engine
-----------------------------------------------------------
Updated in-place to dynamically model incoming State of Charge (SOC)
and support clean parameter tuning via the main control panel.
"""

class VertiportDES:
    def __init__(self, num_pads=2, servicing_strategy="HYBRID", arrival_rate_per_hr=8.0, sim_duration_hrs=24.0):
        self.num_pads = num_pads
        self.servicing_strategy = servicing_strategy  # "FAST_CHARGE", "SWAP", or "HYBRID"
        self.interarrival_mean_min = 60.0 / arrival_rate_per_hr
        self.sim_duration_min = sim_duration_hrs * 60.0

        # Simulation State
        self.env_time = 0.0
        self.event_queue = [] # Priority queue of (event_time, event_type, aircraft_id, data)
        self.free_pads = num_pads

        # Queue & Metrics Tracking
        self.waiting_queue = []
        self.completed_turnarounds = []
        self.pad_occupancy_log = [] # (time, occupied_pads)
        self.next_aircraft_id = 1

        # Additional metrics tracking
        self.queue_length_log = [] # List of (time, queue_length)
        self.max_queue_length = 0
        self.total_arrivals = 0

    def schedule_event(self, delay, event_type, aircraft_id, extra_data=None):
        event_time = self.env_time + delay
        heapq.heappush(self.event_queue, (event_time, event_type, aircraft_id, extra_data))

    def sample_stage_durations(self):
        # Stage 1: Touchdown & Taxi (Triangular: min=1.0, mode=1.5, max=2.5)
        t_land = random.triangular(1.0, 2.5, 1.5)

        # Stage 2: AOI Drone Inspection (Lognormal: mean=1.2, sigma=0.15)
        t_aoi = min(1.5, np.random.lognormal(mean=np.log(1.2), sigma=0.15))

        # State of Charge (SOC) tracking
        soc_arr = random.uniform(0.15, 0.35)

        # Stage 3: Servicing with dynamic SOC
        if self.servicing_strategy == "FAST_CHARGE":
            # Scale the charge time linearly based on required charge (1.0 - SOC_arr)
            base_charge_time = np.random.normal(10.0, 1.5)
            t_service = base_charge_time * (1.0 - soc_arr)
        elif self.servicing_strategy == "SWAP":
            t_service = np.random.normal(2.5, 0.3)
        else: # HYBRID (80% swap during peak, 20% charge)
            if random.random() < 0.8:
                t_service = np.random.normal(2.5, 0.3)
            else:
                base_charge_time = np.random.normal(10.0, 1.5)
                t_service = base_charge_time * (1.0 - soc_arr)

        t_service = max(1.0, t_service)

        # Stage 4: Passenger Egress/Ingress (Triangular: min=1.5, mode=2.0, max=3.0)
        t_pax = random.triangular(1.5, 3.0, 2.0)

        # Stage 5: Pre-Flight & Departure (Triangular: min=0.8, mode=1.0, max=1.5)
        t_dep = random.triangular(0.8, 1.5, 1.0)

        total_service_time = t_land + t_aoi + t_service + t_pax + t_dep

        self.current_soc_arr = soc_arr
        self.current_charge_time = t_service if self.servicing_strategy != "SWAP" else 0.0

        return total_service_time

    def run(self):
        # Schedule first arrival
        first_arrival = random.expovariate(1.0 / self.interarrival_mean_min)
        self.schedule_event(first_arrival, "ARRIVAL", self.next_aircraft_id)
        self.next_aircraft_id += 1

        while self.event_queue:
            event_time, event_type, ac_id, extra_data = heapq.heappop(self.event_queue)
            self.env_time = event_time

            if self.env_time > self.sim_duration_min:
                break

            self.pad_occupancy_log.append((self.env_time, self.num_pads - self.free_pads))
            self.queue_length_log.append((self.env_time, len(self.waiting_queue)))

            if event_type == "ARRIVAL":
                self.total_arrivals += 1
                next_arr_delay = random.expovariate(1.0 / self.interarrival_mean_min)
                self.schedule_event(next_arr_delay, "ARRIVAL", self.next_aircraft_id)
                self.next_aircraft_id += 1

                if self.free_pads > 0:
                    self.free_pads -= 1
                    service_time = self.sample_stage_durations()
                    self.schedule_event(service_time, "DEPARTURE", ac_id, {
                        "arr_time": self.env_time,
                        "wait_time": 0.0,
                        "service_time": service_time,
                        "soc_arrival": self.current_soc_arr,
                        "charge_duration": self.current_charge_time
                    })
                else:
                    self.waiting_queue.append((ac_id, self.env_time))
                    current_queue_len = len(self.waiting_queue)
                    self.queue_length_log.append((self.env_time, current_queue_len))
                    if current_queue_len > self.max_queue_length:
                        self.max_queue_length = current_queue_len

            elif event_type == "DEPARTURE":
                arr_time = extra_data["arr_time"]
                wait_time = extra_data["wait_time"]
                service_time = extra_data["service_time"]
                total_turnaround = wait_time + service_time
                soc_arrival = extra_data.get("soc_arrival", np.nan)
                charge_duration = extra_data.get("charge_duration", np.nan)

                self.completed_turnarounds.append({
                    "ac_id": ac_id,
                    "arr_time": arr_time,
                    "wait_time": wait_time,
                    "service_time": service_time,
                    "total_turnaround": total_turnaround,
                    "soc_arrival": soc_arrival,
                    "charge_duration": charge_duration,
                    "compliant": total_turnaround <= 12.0
                })

                if len(self.waiting_queue) > 0:
                    next_ac_id, next_ac_arr = self.waiting_queue.pop(0)
                    self.queue_length_log.append((self.env_time, len(self.waiting_queue)))
                    wait_time = self.env_time - next_ac_arr
                    service_time = self.sample_stage_durations()
                    self.schedule_event(service_time, "DEPARTURE", next_ac_id, {
                        "arr_time": next_ac_arr,
                        "wait_time": wait_time,
                        "service_time": service_time,
                        "soc_arrival": self.current_soc_arr,
                        "charge_duration": self.current_charge_time
                    })
                else:
                    self.free_pads += 1

        return pd.DataFrame(self.completed_turnarounds)

    def get_average_waiting_queue(self):
        if not self.queue_length_log:
            return 0.0

        total_weighted_time = 0.0
        total_duration = self.env_time

        for i in range(len(self.queue_length_log) - 1):
            t_current, q_len = self.queue_length_log[i]
            t_next, _ = self.queue_length_log[i+1]
            duration = t_next - t_current
            total_weighted_time += q_len * duration

        if self.queue_length_log:
            t_last, q_len = self.queue_length_log[-1]
            if self.sim_duration_min > t_last:
                total_weighted_time += q_len * (self.sim_duration_min - t_last)
                total_duration = self.sim_duration_min

        return total_weighted_time / total_duration if total_duration > 0 else 0.0

